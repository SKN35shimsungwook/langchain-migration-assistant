def after_line(anchor, add):
    global s
    i = s.index(anchor); j = s.index("\n", i) + 1
    s = s[:j] + add + s[j:]
def rep(a, b):
    global s
    assert s.count(a) == 1, a[:50]; s = s.replace(a, b)

